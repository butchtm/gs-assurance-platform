from dataclasses import dataclass
from typing import Optional
from datetime import datetime
from dataclass_wizard import JSONWizard


@dataclass
class RequestCreateUpdate(JSONWizard):
    id: Optional[int] = None  # null for create as autogenerated
    start_date: Optional[datetime] = None
    end_date: Optional[datetime] = None
    booking_date: Optional[datetime] = None
    request_type_id: Optional[int] = None  # PositiveOrZero constraint not directly supported in dataclasses
    request_status_id: Optional[int] = None  # required for update not create
    crediting_period: Optional[int] = None
    invoice_id: Optional[int] = None  # required for update not create
    emission_reduction_amount: Optional[int] = None
    manually_added: Optional[bool] = None
    start_stakeholder_consultation: Optional[bool] = None

