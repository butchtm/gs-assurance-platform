ADD FOREIGN KEY (updated_by_user_id) REFERENCES gs.user ON DELETE RESTRICT;

ALTER TABLE gs.project
ADD COLUMN last_status_change_date timestamp NULL;

ALTER TABLE gs.project_status_history
ADD COLUMN updated_by_user_id int4 NULL;

ALTER TABLE gs.project_status_history
ADD FOREIGN KEY (updated_by_user_id) REFERENCES gs.user ON DELETE RESTRICT;

ALTER TABLE gs.project_status_history
ADD COLUMN changed_at timestamp NULL;

ALTER TABLE gs.project_status_history
ALTER COLUMN previous_status_id DROP NOT NULL; 

-- create the project status history sequence
CREATE SEQUENCE
  gs.project_status_history_id_seq
AS
  integer
OWNED BY
  gs.project_status_history.id;

-- offset the next id to be generated by a margin from migrated project_status_history
SELECT
  setval('gs.project_status_history_id_seq', (SELECT 1000 + max(id) FROM gs.project_status_history));

-- wire the sequence into the id column
ALTER TABLE gs.project_status_history
ALTER COLUMN id SET DEFAULT nextval('gs.project_status_history_id_seq');

-- permissions for back-end
GRANT USAGE, SELECT ON gs.project_status_history_id_seq TO gs_assurance_db_writer;

--
-- Project status history triggers
--
CREATE OR REPLACE FUNCTION
  gs.project_status_change_date_trigger()
RETURNS TRIGGER AS '
    BEGIN
        IF (TG_OP = ''INSERT'' OR (
            TG_OP = ''UPDATE'' AND
            OLD.project_status_id != NEW.project_status_id
            )) THEN
                NEW.last_status_change_date = NOW();
        END IF;
        RETURN NEW;
    END;
' LANGUAGE plpgsql;

CREATE TRIGGER                capture_project_status_change_date
BEFORE INSERT OR UPDATE ON    gs.project
FOR EACH ROW EXECUTE FUNCTION gs.project_status_change_date_trigger();

CREATE OR REPLACE FUNCTION
  gs.project_status_history_trigger()
RETURNS TRIGGER AS '
    BEGIN
        IF (TG_OP = ''INSERT'' OR (
            TG_OP = ''UPDATE'' AND
            OLD.project_status_id != NEW.project_status_id
            )) THEN
                INSERT INTO gs.project_status_history
                    (base_project_id,
                     previous_status_id,
                     next_status_id,
                     changed_at,
                     updated_by_user_id)
                VALUES
                    (NEW.id,
                     OLD.project_status_id,
                     NEW.project_status_id,
                     NEW.last_status_change_date,
                     NEW.updated_by_user_id);
        END IF;
        RETURN NULL;
    END;
' LANGUAGE plpgsql;

CREATE TRIGGER                capture_project_status_history
AFTER INSERT OR UPDATE ON     gs.project
FOR EACH ROW EXECUTE FUNCTION gs.project_status_history_trigger();
