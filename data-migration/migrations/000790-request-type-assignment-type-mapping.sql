CREATE TABLE gs.request_type_assignment_type (
    request_type_id int4 NOT NULL,
    assignment_type_id int4 NOT NULL,
    mandatory boolean NOT NULL,
    PRIMARY KEY (request_type_id, assignment_type_id)
);

ALTER TABLE gs.request_type_assignment_type
ADD FOREIGN KEY (request_type_id) REFERENCES gs.request_type ON DELETE RESTRICT;

ALTER TABLE gs.request_type_assignment_type
ADD FOREIGN KEY (assignment_type_id) REFERENCES gs.assignment_type ON DELETE RESTRICT;

INSERT INTO gs.request_type_assignment_type
  (request_type_id, assignment_type_id, mandatory)
SELECT
  rt.id, at1.id, m.mandatory
FROM
  pg_temp.temp_request_assignment_map m
JOIN
  gs.request_type rt
ON
  m.request_type_code = rt.code
JOIN
  gs.assignment_type at1
ON
  m.assignment_type_code = at1.code
-- only set up mappings for new request types (and work round new and old PRELIMINARY_REVIEW)  
WHERE rt.is_active = true
;

GRANT SELECT ON gs.request_type_assignment_type TO gs_assurance_db_writer;