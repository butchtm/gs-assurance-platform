--
ALTER TABLE gs.request
ADD COLUMN updated_by_user_id int4 NULL;

ALTER TABLE gs.request
ADD FOREIGN KEY (updated_by_user_id) REFERENCES gs.user ON DELETE RESTRICT;

ALTER TABLE gs.request_status_history
ADD COLUMN updated_by_user_id int4 NULL;

ALTER TABLE gs.request_status_history
ADD FOREIGN KEY (updated_by_user_id) REFERENCES gs.user ON DELETE RESTRICT;

ALTER TABLE gs.request_status_history
ALTER COLUMN changed_by DROP NOT NULL;

ALTER TABLE gs.request_status_history
ALTER COLUMN previous_status_id DROP NOT NULL;

-- create the request status history sequence
CREATE SEQUENCE
  gs.request_status_history_id_seq
AS
  integer
OWNED BY
  gs.request_status_history.id;

-- offset the next id to be generated by a margin from migrated request_status_history
SELECT
  setval('gs.request_status_history_id_seq', (SELECT 1000 + max(id) FROM gs.request_status_history));

-- wire the sequence into the id column
ALTER TABLE gs.request_status_history
ALTER COLUMN id SET DEFAULT nextval('gs.request_status_history_id_seq');

-- permissions for back-end
GRANT USAGE, SELECT ON gs.request_status_history_id_seq TO gs_assurance_db_writer;

--
-- Request status history triggers
--
CREATE OR REPLACE FUNCTION
  gs.request_status_change_date_trigger()
RETURNS TRIGGER AS '
    BEGIN
        IF (TG_OP = ''INSERT'' OR (
            TG_OP = ''UPDATE'' AND
            OLD.current_request_status_id != NEW.current_request_status_id
            )) THEN
                NEW.last_request_status_change_date = NOW();
        END IF;
        RETURN NEW;
    END;
' LANGUAGE plpgsql;

CREATE TRIGGER                capture_request_status_change_date
BEFORE INSERT OR UPDATE ON    gs.request
FOR EACH ROW EXECUTE FUNCTION gs.request_status_change_date_trigger();

CREATE OR REPLACE FUNCTION
  gs.request_status_history_trigger()
RETURNS TRIGGER AS '
    BEGIN
        IF (TG_OP = ''INSERT'' OR (
            TG_OP = ''UPDATE'' AND
            OLD.current_request_status_id != NEW.current_request_status_id
            )) THEN
                INSERT INTO gs.request_status_history
                    (request_id,
                     previous_status_id,
                     next_status_id,
                     changed_at,
                     updated_by_user_id)
                VALUES
                    (NEW.id,
                     OLD.current_request_status_id,
                     NEW.current_request_status_id,
                     NEW.last_request_status_change_date,
                     NEW.updated_by_user_id);
        END IF;
        RETURN NULL;
    END;
' LANGUAGE plpgsql;

CREATE TRIGGER                capture_request_status_history
AFTER INSERT OR UPDATE ON     gs.request
FOR EACH ROW EXECUTE FUNCTION gs.request_status_history_trigger();
