DROP TABLE IF EXISTS gs.request_type_document_type;
CREATE TABLE gs.request_type_document_type (
    request_type_id int4 NOT NULL,
    document_type_id int4 NOT NULL,
    document_display_category_id int4 NOT NULL,
    PRIMARY KEY (request_type_id, document_type_id)
);

ALTER TABLE gs.request_type_document_type
ADD FOREIGN KEY (request_type_id) REFERENCES gs.request_type ON DELETE RESTRICT;

ALTER TABLE gs.request_type_document_type
ADD FOREIGN KEY (document_type_id) REFERENCES gs.document_type ON DELETE RESTRICT;

ALTER TABLE gs.request_type_document_type
ADD FOREIGN KEY (document_display_category_id) REFERENCES gs.request_type ON DELETE RESTRICT;

--
-- Populate the actual mapping table by looking up the spready values in associated enums
-- We use left joins to surface unmappable input - it'll error here
--
INSERT INTO gs.request_type_document_type (
	request_type_id,
    document_type_id,
    document_display_category_id
)
SELECT
  rt.id,
  dt.id,
  ddc.id
FROM
  gs.temp_gs_new_mappings gnm
LEFT JOIN
  gs.request_type rt
ON
  gnm.request_type = rt.code AND
  rt.is_active = true
LEFT JOIN
  gs.document_type dt
ON
  gnm.document_type = dt.code AND
  dt.is_active = true
LEFT JOIN
  gs.document_display_category ddc
ON
  gnm.display_category = ddc.code
;