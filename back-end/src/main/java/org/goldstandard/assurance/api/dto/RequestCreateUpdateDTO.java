package org.goldstandard.assurance.api.dto;

import jakarta.validation.Valid;
import jakarta.validation.constraints.PositiveOrZero;
import java.time.ZonedDateTime;
import java.util.List;
import java.util.Optional;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.RequiredArgsConstructor;
import org.apache.commons.collections4.CollectionUtils;
import org.goldstandard.assurance.api.dto.validator.RequestCreditingPeriod;
import org.goldstandard.assurance.api.dto.validator.RequestMonitoringPeriod;
import org.goldstandard.assurance.api.entity.Request;

@Getter
@Builder(toBuilder = true)
@RequiredArgsConstructor
@NoArgsConstructor(force = true)
public class RequestCreateUpdateDTO {
  private final Integer id; // null for create as autogenerated
  private final ZonedDateTime startDate;
  @PositiveOrZero private final Integer requestTypeId;
  private final Integer requestStatusId; // required for update not create
  private final Integer invoiceId; // required for update not create
  private final Integer emissionReductionAmount;
  private final Boolean manuallyAdded;
  private final Boolean startStakeholderConsultation;
  private final Boolean fastTrack;
  private final Boolean internal;
  private final @RequestCreditingPeriod @Valid CreditingPeriodDTO creditingPeriod;
  private final @RequestMonitoringPeriod @Valid MonitoringPeriodDTO monitoringPeriod;
  private final List<@Valid RequestMethodologyDTO> methodologies;
  private final Integer cancellationReasonId;
  private final String otherCancellationReason;

  public boolean shouldStartConsultation() {
    return Boolean.TRUE.equals(startStakeholderConsultation);
  }

  public boolean isFastTrack() {
    return Boolean.TRUE.equals(fastTrack);
  }

  public boolean containsNewCreditingPeriod() {
    return Optional.ofNullable(creditingPeriod)
        .map(CreditingPeriodDTO::isNewCreditingPeriod)
        .orElse(false);
  }

  public boolean containsNewMonitoringPeriod() {
    return Optional.ofNullable(monitoringPeriod)
        .map(MonitoringPeriodDTO::isNewMonitoringPeriod)
        .orElse(false);
  }

  public boolean containsUpdatesToMonitoringPeriod(Request request) {
    if (Optional.ofNullable(monitoringPeriod).isPresent()) {
      return monitoringPeriod.isUpdatedMonitoringPeriod(request);
    }
    return false;
  }

  public boolean hasMethodologies() {
    return Optional.ofNullable(creditingPeriod)
        .map(cp -> CollectionUtils.isNotEmpty(cp.getMethodologies()))
        .orElse(false);
  }
}
