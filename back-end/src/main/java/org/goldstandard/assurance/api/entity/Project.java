package org.goldstandard.assurance.api.entity;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.databind.annotation.JsonSerialize;
import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.JoinTable;
import jakarta.persistence.ManyToMany;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OneToOne;
import jakarta.persistence.PrimaryKeyJoinColumn;
import java.time.ZonedDateTime;
import java.util.Collection;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.function.BinaryOperator;
import java.util.function.Function;
import java.util.stream.Collectors;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.With;
import org.apache.commons.collections4.CollectionUtils;
import org.goldstandard.assurance.api.entity.creditingperiod.ProjectCreditingMonitoringPeriod;
import org.goldstandard.assurance.api.entity.creditingperiod.ProjectCreditingPeriod;
import org.goldstandard.assurance.api.entity.creditingperiod.ProjectCreditingPeriodMethodology;
import org.goldstandard.assurance.api.entity.lookup.Bundle;
import org.goldstandard.assurance.api.entity.lookup.CarbonStream;
import org.goldstandard.assurance.api.entity.lookup.CurrentStandardVersion;
import org.goldstandard.assurance.api.entity.lookup.FeeSchedule;
import org.goldstandard.assurance.api.entity.lookup.Methodology;
import org.goldstandard.assurance.api.entity.lookup.ProjectAsset;
import org.goldstandard.assurance.api.entity.lookup.ProjectClassification;
import org.goldstandard.assurance.api.entity.lookup.ProjectLocation;
import org.goldstandard.assurance.api.entity.lookup.ProjectSize;
import org.goldstandard.assurance.api.entity.lookup.ProjectStatus;
import org.goldstandard.assurance.api.entity.lookup.ProjectType;
import org.goldstandard.assurance.api.entity.lookup.ReferenceDataType;
import org.goldstandard.assurance.api.entity.lookup.RegistrationType;
import org.goldstandard.assurance.api.entity.lookup.SustainableDevelopmentGoal;
import org.goldstandard.assurance.api.util.ProjectIdOnlySerializer;
import org.hibernate.annotations.Fetch;
import org.hibernate.annotations.FetchMode;

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder(toBuilder = true)
@Entity
public class Project {

  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  @Column(name = "id")
  private Integer id;

  @Column(insertable = false, updatable = false) // It's generated by the database
  private String gsid;

  @Column(insertable = false, updatable = false) // It's generated by the database
  private Integer gsidNum;

  private Boolean status;
  private String name;
  private String description;
  @ManyToOne private ProjectClassification projectClassification;
  private ZonedDateTime projectStartDate;
  @ManyToOne private RegistrationType registrationType;
  private Boolean hasProjectAssets;
  @ManyToOne private CarbonStream carbonStream;
  @ManyToOne private CurrentStandardVersion currentStandardVersion;
  @ManyToOne private ProjectSize projectSize;
  private Integer currentRequestId;
  @ManyToOne private ProjectStatus projectStatus;
  @ManyToOne private Bundle bundle;
  private ZonedDateTime designCertificationDate;
  private Boolean designCertificationDateManualSet;
  @ManyToOne private FeeSchedule feeSchedule;
  private Integer estimatedAnnualUnits;

  @ManyToOne
  @JsonSerialize(using = ProjectIdOnlySerializer.class)
  private Project masterProject;

  @ManyToOne
  @JsonSerialize(using = ProjectIdOnlySerializer.class)
  private Project parentProject;

  private ZonedDateTime listingDate;
  private Boolean listingDateManualSet;
  private Integer accountId;

  @OneToOne(mappedBy = "project", cascade = CascadeType.ALL)
  @PrimaryKeyJoinColumn
  private TransitionProject transitionProject;

  @Fetch(FetchMode.JOIN)
  @ManyToMany
  @JoinTable(
      name = "project_project_type",
      joinColumns = @JoinColumn(name = "project_id", referencedColumnName = "id"),
      inverseJoinColumns = @JoinColumn(name = "project_type_id", referencedColumnName = "id"))
  private List<ProjectType> projectTypes;

  @Fetch(FetchMode.JOIN)
  @ManyToMany
  @JoinTable(
      name = "project_project_location",
      joinColumns = @JoinColumn(name = "project_id", referencedColumnName = "id"),
      inverseJoinColumns = @JoinColumn(name = "project_location_id", referencedColumnName = "id"))
  private List<ProjectLocation> projectLocations;

  @Fetch(FetchMode.JOIN)
  @ManyToMany
  @JoinTable(
      name = "project_project_asset",
      joinColumns = @JoinColumn(name = "project_id", referencedColumnName = "id"),
      inverseJoinColumns = @JoinColumn(name = "project_asset_id", referencedColumnName = "id"))
  private List<ProjectAsset> projectAssets;

  @Fetch(FetchMode.JOIN)
  @ManyToMany
  @JoinTable(
      name = "project_sustainable_development_goal",
      joinColumns = @JoinColumn(name = "project_id", referencedColumnName = "id"),
      inverseJoinColumns =
          @JoinColumn(name = "sustainable_development_goal_id", referencedColumnName = "id"))
  private List<SustainableDevelopmentGoal> sustainableDevelopmentGoals;

  @Fetch(FetchMode.JOIN)
  @ManyToMany
  @JoinTable(
      name = "project_methodology",
      joinColumns = @JoinColumn(name = "project_id", referencedColumnName = "id"),
      inverseJoinColumns = @JoinColumn(name = "methodology_id", referencedColumnName = "id"))
  private List<Methodology> methodologies;

  @Fetch(FetchMode.JOIN)
  @OneToMany(mappedBy = "project")
  @With
  private Collection<ProjectCreditingPeriod> creditingPeriods;

  private ZonedDateTime lastActivity;
  private String notes;
  private ZonedDateTime certifiedProjectDate;
  private ZonedDateTime lastDesignCertificationRenewalDate;
  private ZonedDateTime lastPerformanceReviewDate;

  private Integer updatedByUserId;

  @Column(insertable = false, updatable = false)
  private ZonedDateTime lastStatusChangeDate;

  @Column(insertable = false, updatable = false)
  private Boolean migrated;

  private Boolean displayNotRequestedStatusRequests;

  private Integer registryId;

  public Project(Integer id) {
    this.id = id;
  }

  public boolean hasSameMasterAs(Project otherProject) {
    return hasMaster(otherProject.getMasterProject());
  }

  public boolean hasMaster(Project otherProject) {
    return haveSameIds(masterProject, otherProject);
  }

  public boolean hasParent(Project otherProject) {
    return haveSameIds(parentProject, otherProject);
  }

  @JsonIgnore
  public boolean isPoa() {
    return projectClassification.isPoa();
  }

  @JsonIgnore
  public boolean isRegularCaseVpa() {
    return projectClassification.isRegularCaseVpa();
  }

  @JsonIgnore
  public boolean isLegacyVpaCpa() {
    return projectClassification.isLegacyVpaCpa();
  }

  @JsonIgnore
  public boolean isRealCaseVpa() {
    return projectClassification.isRealCaseVpa();
  }

  public Project withTransitionProject(TransitionProject transitionProject) {
    var updated = toBuilder().build();
    updated.setTransitionProject(transitionProject);
    return updated;
  }

  public void setTransitionProject(TransitionProject transitionProject) {
    this.transitionProject = transitionProject;
    if (transitionProject != null) {
      this.transitionProject.setProject(this);
    }
  }

  @JsonIgnore
  public boolean isNew() {
    if (Objects.isNull(projectStatus)) {
      return false;
    }
    return projectStatus.isNew();
  }

  public Project withProjectStatus(ProjectStatus status, ZonedDateTime date) {
    if (status.isListed()) {
      return withListedStatus(status, date);
    }
    if (status.isDesignCertified()) {
      return withDesignCertifiedStatus(status, date);
    }
    if (status.isCertifiedProject()) {
      return withCertifiedProjectStatus(status, date);
    }
    return toBuilder().projectStatus(status).build();
  }

  @JsonIgnore
  public int getNextCreditingPeriodId() {
    return getLatestCreditingPeriodId() + 1;
  }

  @JsonIgnore
  public boolean shouldDisplayNotRequestedStatusRequests() {
    return Boolean.TRUE.equals(displayNotRequestedStatusRequests);
  }

  @JsonIgnore
  public Optional<Integer> getLatestFeeScheduleId() {
    if (CollectionUtils.isEmpty(creditingPeriods)) {
      return getProjectFeeScheduleId();
    }
    return creditingPeriods.stream()
        .map(ProjectCreditingPeriod::getMonitoringPeriods)
        .flatMap(Collection::stream)
        .filter(monitoringPeriod -> Objects.nonNull(monitoringPeriod.getFeeSchedule()))
        .sorted(Comparator.comparing(ProjectCreditingMonitoringPeriod::getEndDate).reversed())
        .map(ProjectCreditingMonitoringPeriod::getFeeSchedule)
        .findFirst()
        .or(this::getProjectFeeScheduleId);
  }

  @JsonIgnore
  public boolean isMicroscale() {
    return Optional.ofNullable(projectSize).map(ProjectSize::isMicroscale).orElse(false);
  }

  @JsonIgnore
  public boolean inLeastDevelopedCountry() {
    if (CollectionUtils.isEmpty(projectLocations)) {
      return false;
    }
    return projectLocations.stream().anyMatch(ProjectLocation::isLeastDevelopedCountry);
  }

  @JsonIgnore
  public boolean isMigrated() {
    return Boolean.TRUE.equals(migrated);
  }

  @JsonIgnore
  public Collection<Methodology> getAllMethodologies() {
    BinaryOperator<Methodology> ignoreDuplicates = (m1, m2) -> m1;
    var legacyMap =
        Optional.ofNullable(methodologies).stream()
            .flatMap(Collection::stream)
            .collect(
                Collectors.toMap(ReferenceDataType::getId, Function.identity(), ignoreDuplicates));
    var map =
        Optional.ofNullable(creditingPeriods).stream()
            .flatMap(Collection::stream)
            .map(ProjectCreditingPeriod::getMethodologies)
            .flatMap(Collection::stream)
            .map(ProjectCreditingPeriodMethodology::getMethodology)
            .collect(
                Collectors.toMap(ReferenceDataType::getId, Function.identity(), ignoreDuplicates));
    var allMap = new HashMap<>(legacyMap);
    allMap.putAll(map);
    return allMap.values();
  }

  public Optional<Integer> getRegistryId() {
    return Optional.ofNullable(registryId);
  }

  private int getLatestCreditingPeriodId() {
    if (CollectionUtils.isEmpty(creditingPeriods)) {
      return 0;
    }
    return creditingPeriods.stream().mapToInt(ProjectCreditingPeriod::getPeriodId).max().orElse(0);
  }

  private Optional<Integer> getProjectFeeScheduleId() {
    return Optional.ofNullable(feeSchedule).map(ReferenceDataType::getId);
  }

  private Project withListedStatus(ProjectStatus status, ZonedDateTime date) {
    return toBuilder().projectStatus(status).listingDate(date).build();
  }

  private Project withDesignCertifiedStatus(ProjectStatus status, ZonedDateTime date) {
    var builder = toBuilder().projectStatus(status).designCertificationDate(date);
    if (Objects.isNull(listingDate)) {
      builder.listingDate(date);
    }
    return builder.build();
  }

  private Project withCertifiedProjectStatus(ProjectStatus status, ZonedDateTime date) {
    var builder = toBuilder().projectStatus(status).certifiedProjectDate(date);
    if (Objects.isNull(designCertificationDate)) {
      builder.designCertificationDate(date);
    }
    if (Objects.isNull(listingDate)) {
      builder.listingDate(date);
    }
    return builder.build();
  }

  public static boolean hasSameParentAndNotSameId(Project project1, Project project2) {
    return project1.hasParent(project2.getParentProject()) && !haveSameIds(project1, project2);
  }

  private static boolean haveSameIds(Project project1, Project project2) {
    if (Objects.isNull(project1)) {
      return false;
    }
    return Objects.equals(project1.getId(), project2.getId());
  }
}
